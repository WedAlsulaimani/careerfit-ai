export const MAX_UPLOAD_BYTES = 10 * 1024 * 1024;
export const MAX_JOB_IMAGE_BYTES = 8 * 1024 * 1024;

export type DetectedType = { mime: "application/pdf" | "image/png" | "image/jpeg" | "image/webp"; ext: "pdf" | "png" | "jpg" | "webp" };

/** Identifies a file by its magic bytes (the declared MIME type is not trusted). */
export function detectFileType(bytes: Uint8Array): DetectedType | null {
  const b = bytes;
  if (b.length >= 5 && b[0] === 0x25 && b[1] === 0x50 && b[2] === 0x44 && b[3] === 0x46 && b[4] === 0x2d) {
    return { mime: "application/pdf", ext: "pdf" };
  }
  if (b.length >= 8 && b[0] === 0x89 && b[1] === 0x50 && b[2] === 0x4e && b[3] === 0x47 && b[4] === 0x0d && b[5] === 0x0a && b[6] === 0x1a && b[7] === 0x0a) {
    return { mime: "image/png", ext: "png" };
  }
  if (b.length >= 3 && b[0] === 0xff && b[1] === 0xd8 && b[2] === 0xff) {
    return { mime: "image/jpeg", ext: "jpg" };
  }
  if (
    b.length >= 12 &&
    b[0] === 0x52 && b[1] === 0x49 && b[2] === 0x46 && b[3] === 0x46 &&
    b[8] === 0x57 && b[9] === 0x45 && b[10] === 0x42 && b[11] === 0x50
  ) {
    return { mime: "image/webp", ext: "webp" };
  }
  return null;
}

export function isJobImage(t: DetectedType | null): boolean {
  return !!t && t.mime !== "application/pdf";
}
